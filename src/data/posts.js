/**
 * Format a post for display in PostCard component
 */
export const formatPost = (post) => ({
  id: post.id,
  slug: post.slug,
  image: post.coverImage,
  categories: post.tags,
  title: post.title,
  excerpt: post.excerpt,
  date: new Date(post.publishedAt).toLocaleDateString('es-ES', {
    day: '2-digit',
    month: '2-digit',
    year: 'numeric'
  }),
  readTime: `${post.readTime} minutos de lectura`
});

/**
 * Get all posts formatted for display
 */
export const getFormattedPosts = () => {
  return posts.map(formatPost);
};

/**
 * Filter posts based on search term, categories, and products
 */
export const filterPosts = (searchTerm = '', selectedCategories = [], selectedProducts = []) => {
  const formattedPosts = getFormattedPosts();
  
  return formattedPosts.filter(post => {
    // Search filter
    const matchesSearch = !searchTerm || 
      post.title.toLowerCase().includes(searchTerm.toLowerCase()) ||
      post.excerpt.toLowerCase().includes(searchTerm.toLowerCase());
    
    // Category filter
    const matchesCategory = selectedCategories.length === 0 || 
      selectedCategories.some(cat => post.categories.includes(cat));
    
    // Product filter
    const matchesProduct = selectedProducts.length === 0 || 
      selectedProducts.some(tag => post.categories.includes(tag));
    
    return matchesSearch && matchesCategory && matchesProduct;
  });
};

/**
 * Paginate posts
 */
export const paginatePosts = (posts, page = 1, postsPerPage = 6) => {
  const indexOfLastPost = page * postsPerPage;
  const indexOfFirstPost = indexOfLastPost - postsPerPage;
  const currentPosts = posts.slice(indexOfFirstPost, indexOfLastPost);
  const totalPages = Math.ceil(posts.length / postsPerPage);
  
  return {
    currentPosts,
    totalPages,
    currentPage: page,
    totalPosts: posts.length
  };
};

/**
 * Get filtered and paginated posts
 */
export const getFilteredPaginatedPosts = (
  searchTerm = '', 
  selectedCategories = [], 
  selectedProducts = [], 
  page = 1, 
  postsPerPage = 6,
  skipFirst = false
) => {
  let filtered = filterPosts(searchTerm, selectedCategories, selectedProducts);
  
  // Skip first post if requested (used when first post is featured elsewhere)
  if (skipFirst) {
    filtered = filtered.slice(1);
  }
  
  return paginatePosts(filtered, page, postsPerPage);
};
